@pytest.mark.unit
def test_the_real_package_produces_a_real_identity() -> None:
    """Guards against the helper silently degrading to "unknown" in the
    installed layout, which would make every assertion above vacuous in prod."""
    identity = code_identity()

    assert identity.sha != "unknown"
    assert len(identity.sha) == 12
    assert identity.file_count > 100, identity
    assert identity.source_root.endswith("hft_platform")


@pytest.mark.unit
def test_the_build_info_gauge_exposes_the_running_code_sha() -> None:
    """``hft_build_info`` is the drift-detection gauge. Until now every label on
    it described the image."""
    from prometheus_client import REGISTRY

    from hft_platform.observability.metrics import MetricsRegistry, _pn

    MetricsRegistry()

    for metric in REGISTRY.collect():
        if metric.name == _pn("build_info"):
            labels = metric.samples[0].labels
            assert labels.get("code_sha") == running_code_sha()
            assert "git_sha" in labels and "build_ts" in labels
            return
    pytest.fail("build_info gauge not found in the Prometheus registry")


@pytest.mark.unit
def test_the_startup_line_names_the_image_and_the_code_separately(monkeypatch, module_log_sink) -> None:
    """Logs are the surface the deploy runbook actually reads. Both identities
    have to be on the line, or the next reader repeats the same mistake."""
    from hft_platform.observability import code_identity as code_identity_module

    events = module_log_sink(code_identity_module)
    monkeypatch.setenv("HFT_GIT_SHA", "bfa46e1d")
    identity = log_code_identity()

    line = next(entry for entry in events if entry.get("event") == "running_code_identity")
    assert line["code_sha"] == identity.sha
    assert line["image_git_sha"] == "bfa46e1d"
    assert line["files"] == identity.file_count


@pytest.mark.unit
def test_the_identity_is_computed_once_per_process() -> None:
    """It walks every source file; boot must pay for that once, not per caller."""
    first = code_identity()

    assert code_identity() is first
